-- Editable website content (admin -> Website content).
-- Run once in the Supabase SQL editor, after 0018_feedback.sql.
-- Safe to deploy the code first: until this is run the public site simply shows
-- its built-in text (nothing is overridden) and the admin screen shows a "not
-- set up yet" card instead of failing.
--
-- Why a table of its own, not another corner of the `store_document` JSON:
-- the document is read and written whole, so a content edit and a menu edit
-- made at the same moment would overwrite each other. Here every field is its
-- own row, so two people can edit two fields at once, and a history is cheap.
--
-- `site_content` holds only what the owner has CHANGED. A field with no row is
-- showing the default that ships in the code (messages/nl.json, messages/en.json),
-- which is exactly what "reset to default" means: delete the row.
--
--   key     what was edited: "home.whyTitle", "home.faq", "layout.home", "media.heroWeb"
--   locale  'nl' or 'en' for text; '*' for things that are not language-specific
--           (section order, the reviews list, which video is shown)
--   value   jsonb: a string for a text field, an array for a list (the FAQ, the
--           marquee), an object for a layout or a media slot
--
-- The app only accepts keys from its own registry (src/lib/content/registry.ts),
-- so this table can never be used to override checkout, legal or system text.

create table if not exists site_content (
  key text not null,
  locale text not null check (locale in ('nl', 'en', '*')),
  value jsonb not null,
  updated_at timestamptz not null default now(),
  -- Who changed it, as the email they signed in with.
  updated_by text,
  primary key (key, locale)
);

-- Every change ever saved, newest last. `value` is null when the change was
-- "reset to default". This is what powers the per-field history and "restore".
create table if not exists site_content_history (
  -- BY DEFAULT (not ALWAYS) so the backup restore can put rows back with their
  -- original ids; with ALWAYS Postgres refuses an explicit id.
  id bigint generated by default as identity primary key,
  key text not null,
  locale text not null check (locale in ('nl', 'en', '*')),
  value jsonb,
  changed_at timestamptz not null default now(),
  changed_by text
);

create index if not exists site_content_history_lookup_idx
  on site_content_history (key, locale, id desc);

-- Server-only, like every table here: reached with the service-role key.
alter table site_content enable row level security;
alter table site_content_history enable row level security;
